// The syntax with destructuring 
{
    const [first, second, third] = ["Laide", "Gabriel", "Jets"];

    console.log(first);
    console.log(second);
    console.log(third);
}


// The syntax without destructuring
{
    const first = "Laide",
      second = "Gabriel",
      third = "Jets";

      console.log(third);
}